/// انتخاب قطعی و روزانه‌ی پیام بر اساس برج و تاریخ امروز؛ یعنی برای هر برج
/// هر روز یک پیام ثابت است، ولی روزهای مختلف پیام‌های متفاوتی می‌گیرند.
String getDailyMessage(String signName, DateTime date) {
  final dateKey = '${date.year}-${date.month}-${date.day}';
  final seed = '$signName-$dateKey';
  int hash = 0;
  for (final char in seed.codeUnits) {
    hash = (hash * 31 + char) & 0x7fffffff;
  }
  final index = hash % dailyMessagePool.length;
  return dailyMessagePool[index];
}
