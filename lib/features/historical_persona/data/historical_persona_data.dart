/// انتخاب قطعی (نه تصادفی) بر اساس تاریخ تولد میلادی — یعنی برای یک نفر
/// همیشه یک نتیجه‌ی ثابت می‌آید، نه هر بار یک چیز متفاوت.
HistoricalPersona getHistoricalPersona(int day, int month, int year) {
  final seed = day * 31 + month * 12 + year;
  final index = seed % historicalPersonas.length;
  return historicalPersonas[index];
}
