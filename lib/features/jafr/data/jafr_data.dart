/// محاسبه‌ی جفر: طبق رسم سنتی، معمولاً از ترکیب نام شخص و نام مادر استفاده
/// می‌شود (برخلاف ذکر ابجد که فقط از نام خود شخص استفاده می‌کرد).
JafrReading calculateJafrReading(String name, String motherName) {
  final combined = calculateAbjadValue(name) + calculateAbjadValue(motherName) * 2;
  final index = combined % jafrReadings.length;
  return jafrReadings[index];
}
