/// انتخاب قطعی و روزانه‌ی چند جمله (پیش‌فرض ۵ تا) از استخر مربوط به عدد مسیر
/// زندگی؛ یعنی هر روز جمله‌های متفاوتی می‌آید ولی برای یک روز مشخص، ثابت است.
List<String> getDailySentences(int lifePathNumber, DateTime date, {int count = 5}) {
  final pool = dailySentencesByLifePath[lifePathNumber];
  if (pool == null || pool.isEmpty) return [];

  final dateKey = '${date.year}-${date.month}-${date.day}';
  final seedBase = '$lifePathNumber-$dateKey';

  int hash = 0;
  for (final char in seedBase.codeUnits) {
    hash = (hash * 31 + char) & 0x7fffffff;
  }

  final startIndex = hash % pool.length;
  final result = <String>[];
  for (int i = 0; i < count && i < pool.length; i++) {
    result.add(pool[(startIndex + i) % pool.length]);
  }
  return result;
}
