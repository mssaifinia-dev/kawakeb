int _sumDigits(int n) {
  return n.toString().split('').map(int.parse).reduce((a, b) => a + b);
}

/// کاهش عدد تا رسیدن به یک رقم، مگر اینکه به یکی از اعداد استاد (۱۱، ۲۲، ۳۳) برسد؛
/// طبق روال رایج در عددشناسی، اعداد استاد دیگر کاهش داده نمی‌شوند.
int reduceWithMasterNumbers(int number) {
  int n = number;
  while (n > 9 && n != 11 && n != 22 && n != 33) {
    n = _sumDigits(n);
  }
  return n;
}
