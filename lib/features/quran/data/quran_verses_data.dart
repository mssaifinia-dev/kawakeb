//
// برخلاف quranVersePool بالا (که یک استخر محدود دستچین‌شده با ۱۵۲ آیه است)،
// این بخش امکان انتخاب واقعاً تصادفی از میان کل قرآن را فراهم می‌کند.
// متن آیات از فایل asset (assets/quran/quran_full.json) خوانده می‌شود، نه
// این‌که مستقیم داخل کد Dart نوشته شده باشد — چون حجم ۶۲۳۶ آیه به‌صورت
// object literal در Dart غیرعملی و کند است. فایل JSON فقط یک‌بار در طول
// عمر اپ خوانده و در حافظه کش می‌شود.

/// یک آیه از کل قرآن، با شماره‌ی سراسری (globalAyahNumber) و مختصات دقیقش
/// (سوره + آیه). متن دقیقاً با رسم عثمانی است.
class FullQuranVerse {
  /// شماره‌ی سراسری آیه از ۱ تا ۶۲۳۶ (بدون توجه به سوره).
  final int globalAyahNumber;

  /// شماره‌ی سوره از ۱ (فاتحه) تا ۱۱۴ (ناس).
  final int surahNumber;

  /// شماره‌ی آیه داخل همان سوره (نه سراسری).
  final int ayahNumber;

  /// نام عربی سوره، مثلاً «البقرة».
  final String surahNameAr;

  /// متن عربی آیه با رسم عثمانی.
  final String verse;

  const FullQuranVerse({
    required this.globalAyahNumber,
    required this.surahNumber,
    required this.ayahNumber,
    required this.surahNameAr,
    required this.verse,
  });

  factory FullQuranVerse.fromJson(Map<String, dynamic> json) {
    return FullQuranVerse(
      globalAyahNumber: json['g'] as int,
      surahNumber: json['s'] as int,
      ayahNumber: json['a'] as int,
      surahNameAr: json['sn'] as String,
      verse: json['t'] as String,
    );
  }
}

/// بارگذاری و کش کل ۶۲۳۶ آیه‌ی قرآن از فایل asset. فقط یک‌بار در طول اجرای
/// اپ واقعاً خوانده می‌شود؛ دفعات بعد از حافظه‌ی کش‌شده برمی‌گردد.
class QuranFullData {
  static List<FullQuranVerse>? _cache;

  static Future<List<FullQuranVerse>> _loadAll() async {
    final cached = _cache;
    if (cached != null) return cached;

    final raw = await rootBundle.loadString('assets/quran/quran_full.json');
    final decoded = jsonDecode(raw) as List<dynamic>;
    final list = decoded
        .map((e) => FullQuranVerse.fromJson(e as Map<String, dynamic>))
        .toList(growable: false);

    // این assert فقط در حالت debug اجرا می‌شود و مطمئن می‌شود دیتاست کامل
    // است؛ اگر یک روز فایل asset خراب/ناقص جایگزین شود، زودتر متوجه می‌شویم.
    assert(list.length == 6236, 'دیتاست قرآن باید دقیقاً ۶۲۳۶ آیه داشته باشد، ${list.length} خوانده شد.');

    _cache = list;
    return list;
  }

  /// یک آیه‌ی کاملاً تصادفی از کل ۶۲۳۶ آیه برمی‌گرداند. چون اندیس تصادفی از
  /// روی طول همان لیستِ واقعاً بارگذاری‌شده انتخاب می‌شود (نه یک عدد ثابت)،
  /// هیچ‌وقت اندیس یا شماره‌ی نامعتبر تولید نمی‌شود.
  static Future<FullQuranVerse> getRandomVerse() async {
    final all = await _loadAll();
    final index = Random().nextInt(all.length);
    return all[index];
  }
}

