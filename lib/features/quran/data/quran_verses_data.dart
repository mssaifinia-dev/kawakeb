const List<String> _istikharaBadGuidance = [
  'در حال حاضر این کار خالی از دغدغه نیست؛ عجله نکن و بیشتر بررسی کن.',
  'شاید بهتر باشه فعلاً این تصمیم رو کنار بگذاری یا به تعویق بندازی.',
