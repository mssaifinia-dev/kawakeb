String pickIndependentIstikharaGuidance(QuranVerdict verdict) {
  switch (verdict) {
    case QuranVerdict.good:
      return _istikharaGoodGuidance[Random().nextInt(_istikharaGoodGuidance.length)];
    case QuranVerdict.moderate:
      return _istikharaModerateGuidance[Random().nextInt(_istikharaModerateGuidance.length)];
    case QuranVerdict.bad:
      return _istikharaBadGuidance[Random().nextInt(_istikharaBadGuidance.length)];
  }
}

/// نتیجه‌ی یکپارچه‌ی استخاره؛ verdict و guidance مستقل از آیه انتخاب
/// می‌شوند (توضیح بالا را ببین).
class IstikharaResult {
  final String verse;
  final String? translation;
  final QuranVerdict verdict;
  final String guidance;
  final String? reference;
  final bool isInterpretive;

  const IstikharaResult({
    required this.verse,
    this.translation,
    required this.verdict,
    required this.guidance,
    this.reference,
    required this.isInterpretive,
  });
}

/// یک آیه‌ی کاملاً تصادفی از کل قرآن برای استخاره انتخاب می‌کند و یک
/// verdict کاملاً مستقل (بدون ارتباط به متن آیه) به آن نسبت می‌دهد.
Future<IstikharaResult> pickRandomIstikhara() async {
  final full = await QuranFullData.getRandomVerse();
  final verdict = pickIndependentVerdict();
  return IstikharaResult(
    verse: full.verse,
    translation: null,
    verdict: verdict,
    guidance: pickIndependentIstikharaGuidance(verdict),
    reference: 'سوره ${full.surahNameAr} — آیه ${full.ayahNumber}',
    isInterpretive: true,
  );
}
