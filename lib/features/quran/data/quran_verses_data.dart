  );
}

// ============================================================================
// بخش استخاره‌ی نسخه‌ی جدید (بر پایه‌ی کل قرآن)
// ============================================================================
//
// نکته‌ی مهم طراحی: بر خلاف نسخه‌ی قدیمی که هر آیه از قبل یک verdict
// (خوب/متوسط/صبرکن) دستچین‌شده داشت، اینجا نمی‌توانیم به ۶۰۸۴ آیه‌ی جدید
// verdict قدیمی را تصادفی نسبت بدهیم — چون این کار یعنی به یک آیه‌ی
// قرآن، بدون هیچ مبنایی، برچسب «بد» یا «خوب» بچسبانیم. به همین دلیل
// انتخاب verdict کاملاً از انتخاب آیه جدا و مستقل طراحی شده: یک قرعه‌ی
// جداگانه با وزن‌های مشخص، که هیچ ربطی به محتوای آیه‌ی انتخاب‌شده ندارد.
// متن راهنمایی هم بر اساس همین verdict مستقل تولید می‌شود، نه بر اساس آیه.

/// قرعه‌ی مستقل verdict — وزن‌ها تقریباً هم‌راستا با توزیع استخر قدیمی است
/// (بیشتر خوب/متوسط، کمتر «صبر کن») ولی هیچ ارتباطی به متن آیه ندارد.
QuranVerdict pickIndependentVerdict() {
  final r = Random().nextDouble();
  if (r < 0.45) return QuranVerdict.good;
  if (r < 0.85) return QuranVerdict.moderate;
  return QuranVerdict.bad;
}

