/// نتیجه‌ی یکپارچه‌ی سرکتاب؛ چه از استخر قدیمی دستچین‌شده بیاید (translation
/// و isInterpretive=false) چه از کل ۶۲۳۶ آیه‌ی قرآن (translation=null و
/// isInterpretive=true).
class SarKetabResult {
  final String verse;
  final String? translation;
  final String guidance;
  final bool isInterpretive;
  final String? reference;

  const SarKetabResult({
    required this.verse,
    this.translation,
    required this.guidance,
    required this.isInterpretive,
    this.reference,
  });
}

/// یک آیه‌ی کاملاً تصادفی از کل قرآن برای سرکتاب انتخاب می‌کند (نسخه‌ی جدید،
/// دیگر محدود به quranVersePool نیست).
Future<SarKetabResult> pickRandomSarKetabVerse() async {
  final full = await QuranFullData.getRandomVerse();
  return SarKetabResult(
    verse: full.verse,
    translation: null,
    guidance: pickGenericInterpretiveGuidance(),
